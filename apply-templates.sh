#!/usr/bin/env bash
# Render tcl<version>/<variant>/Dockerfile; the output is committed.
set -euo pipefail
cd "$(dirname "$0")"

for tcl in $(jq -r '.tcl[]' versions.json); do
	for variant in $(jq -r '.variants | keys[]' versions.json); do
		template=$(jq -r --arg v "$variant" '.variants[$v].template' versions.json)
		mkdir -p "tcl$tcl/$variant"
		{
			echo "# DO NOT EDIT: generated by apply-templates.sh from Dockerfile-$template.template"
			echo
			jq -rRs --slurpfile cfg versions.json --arg tcl "$tcl" --arg variant "$variant" '
				$cfg[0] as $c | $c.variants[$variant] as $v
				| gsub("%%TCL_IMAGE%%"; $c.tclImage)
				| gsub("%%TCL_VERSION%%"; $tcl)
				| gsub("%%TCL_VARIANT%%"; $v.tclVariant // $variant)
				| gsub("%%BUILD_DEPS%%"; $v.buildDeps | join("; \\\n\t"))
				| gsub("%%HTTPD_INCLUDE%%"; $v.httpdInclude)
				| gsub("%%APR_INCLUDE%%"; $v.aprInclude)
				| gsub("%%WEBSH_VERSION%%"; $c.websh.version)
				| gsub("%%WEBSH_COMMIT%%"; $c.websh.commit)
				| gsub("%%WEBSH_SHA256%%"; $c.websh.sha256)
			' "Dockerfile-$template.template"
		} > "tcl$tcl/$variant/Dockerfile"
	done
done
